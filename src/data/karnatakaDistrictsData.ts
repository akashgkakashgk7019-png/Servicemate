export const KARNATAKA_ZONES = [
  'Central Karnataka',
  'Bengaluru Division',
  'Mysuru Division',
  'Belagavi Division',
  'Kalyana Karnataka',
] as const;

export type KarnatakaZone = typeof KARNATAKA_ZONES[number];

export function getDistrictsByZone(zone: string): KarnatakaDistrict[] {
  if (!zone || zone === 'ALL') return KARNATAKA_DISTRICTS;
  return KARNATAKA_DISTRICTS.filter((d) => d.zone === zone);
}

export function getDistrictById(districtId: string): KarnatakaDistrict | undefined {
  return KARNATAKA_DISTRICTS.find((d) => d.id === districtId);
}

export function findDistrictByName(name: string): KarnatakaDistrict | undefined {
  if (!name) return undefined;
  const q = name.toLowerCase().trim();
  return KARNATAKA_DISTRICTS.find(
    (d) =>
      d.name.toLowerCase().includes(q) ||
      d.id.toLowerCase() === q ||
      d.rtoCode.toLowerCase().includes(q) ||
      q.includes(d.name.toLowerCase())
  );
}
